// Strict input validation shared by the renderer (for types) and main (for
// enforcement). Every IPC call is parsed again in main with these helpers.
// No Node or DOM imports: this file is bundled into both processes.

export class InvalidInput extends TypeError {
  constructor() { super('Invalid input'); this.name = 'InvalidInput'; }
}
const invalid = (): never => { throw new InvalidInput(); };

export function record(value: unknown): Record<string, unknown> {
  if (!value || typeof value !== 'object' || Array.isArray(value) || Object.getPrototypeOf(value) !== Object.prototype
    && Object.getPrototypeOf(value) !== null) return invalid();
  return value as Record<string, unknown>;
}

// Exact field set: every required key present, nothing outside required+optional.
export function fields(value: unknown, required: readonly string[], optional: readonly string[] = []): Record<string, unknown> {
  const input = record(value);
  for (const key of Object.keys(input)) if (!required.includes(key) && !optional.includes(key)) invalid();
  for (const key of required) if (!Object.hasOwn(input, key)) invalid();
  return input;
}

const CONTROL = /[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/u;
const LINE_CONTROL = /[\u0000-\u001f\u007f]/u;

// Free text a person typed. Multiline allows tabs and newlines only.
export function text(value: unknown, options: Readonly<{ max: number; min?: number; multiline?: boolean }>): string {
  if (typeof value !== 'string' || value.length < (options.min ?? 1) || value.length > options.max || !value.isWellFormed()
    || (options.multiline ? CONTROL : LINE_CONTROL).test(value)) return invalid();
  return value;
}

// Host identifiers (profile names, job IDs, session IDs): exact, never repaired.
export function identifier(value: unknown, max = 512): string {
  const result = text(value, { max });
  if (result.trim() !== result || /[\u0080-\u009f‪-‮⁦-⁩]/u.test(result)) return invalid();
  return result;
}

// A single URL path segment for a host route: conservative characters only.
export function segment(value: unknown, max = 256): string {
  const result = identifier(value, max);
  if (!/^[A-Za-z0-9_.:@~-]+$/u.test(result) || result === '.' || result === '..') return invalid();
  return result;
}

export function integer(value: unknown, min: number, max: number): number {
  if (typeof value !== 'number' || !Number.isSafeInteger(value) || value < min || value > max) return invalid();
  return value;
}

export function boolean(value: unknown): boolean {
  if (typeof value !== 'boolean') return invalid();
  return value;
}

export function oneOf<T extends string>(value: unknown, values: readonly T[]): T {
  if (typeof value !== 'string' || !values.includes(value as T)) return invalid();
  return value as T;
}

export function list<T>(value: unknown, max: number, item: (entry: unknown) => T): readonly T[] {
  if (!Array.isArray(value) || value.length > max) return invalid();
  return Object.freeze(value.map(item));
}

export function optional<T>(value: unknown, parse: (entry: unknown) => T): T | undefined {
  return value === undefined ? undefined : parse(value);
}

// Lowercase UUID, as generated by crypto.randomUUID() in either process.
export function uuid(value: unknown): string {
  const result = text(value, { max: 36 });
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/u.test(result)) return invalid();
  return result;
}

// Remove undefined members so exactOptionalPropertyTypes holds across IPC.
export function compact<T extends Record<string, unknown>>(value: T): { [K in keyof T]: Exclude<T[K], undefined> } {
  const result: Record<string, unknown> = {};
  for (const [key, entry] of Object.entries(value)) if (entry !== undefined) result[key] = entry;
  return Object.freeze(result) as { [K in keyof T]: Exclude<T[K], undefined> };
}
